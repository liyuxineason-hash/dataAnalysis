"""
study_sort.py   sort() 里的 key 到底是什么？

先看原来的那段代码：

    def takeSecond(elem):
        return elem[1]

    random = [(2, 2), (3, 4), (4, 1), (1, 3)]
    random.sort(key=takeSecond)
    print('排序列表：', random)

一句话结论：
    key 后面跟的是一个函数（只写函数名，不加括号）。
    sort 会先把列表里的每一个元素都丢进这个函数，
    拿到一个"排序依据"，然后按这个依据从小到大排。
    最后留在列表里的仍然是原来的元素，那个"依据"用完就丢掉。

    这里 takeSecond(elem) 返回 elem[1]，也就是"第二个元素"，
    所以这次比较的是每个元组的第 2 个数字：2、4、1、3，
    排完就是 1、2、3、4，对应 [(4, 1), (2, 2), (1, 3), (3, 4)]。

下面每一部分都可以单独跑，建议从上往下看。
"""


# ============================================================
# 第一部分：把原始代码原封不动地跑一遍
# ============================================================
print('=' * 62)
print('第一部分：原始代码，先看结果')
print('=' * 62)


# 获取列表的第二个元素
def takeSecond(elem):
    return elem[1]


# 列表
random = [(2, 2), (3, 4), (4, 1), (1, 3)]

# 指定第二个元素排序
random.sort(key=takeSecond)

# 输出类别
print('排序列表：', random)


# ============================================================
# 第二部分：把 sort 内部做的事情拆开看
# ============================================================
# 注意：key 只写函数名 takeSecond，不要写成 takeSecond()。
#       takeSecond   -> 把函数本身交给 sort
#       takeSecond() -> 调用函数，把返回值交给 sort（这里会直接报错）
#
# sort 的大致流程是：
#   1) 对每个元素调用一次 key 函数，得到"排序依据"
#   2) 按这些排序依据从小到大排列
#   3) 按新顺序把原来的元素摆好
print()
print('=' * 62)
print('第二部分：拆开看 key 到底做了什么')
print('=' * 62)

data = [(2, 2), (3, 4), (4, 1), (1, 3)]

# 手动模拟第 1 步：每个元素 -> 排序依据
keys = [takeSecond(x) for x in data]
print('原来的元素：', data)
print('每个元素经过 takeSecond 之后：', keys)

# 把两边对应着打印出来，方便看清楚"依据"是哪来的
for elem, k in zip(data, keys):
    print(f'  元素 {elem}  ->  takeSecond 返回 {k}')

print('把依据 2、4、1、3 从小到大排好，是 1、2、3、4')
print('再按这个顺序把元素摆回去：', sorted(data, key=takeSecond))


# ============================================================
# 第三部分：不写 key 会怎样？这就回答了"里面有两个元素怎么排"
# ============================================================
# 元组之间比较，是"逐个位置比"：
#   先比第 0 个元素，谁小谁在前；
#   第 0 个相等，再比第 1 个；
#   第 1 个还相等，就继续往后比。
# 这种规则叫"字典序"，跟查字典一样。
#
# 所以不写 key 时，是拿整个元组去比 -> 先看第 1 个数字。
# 写了 key=takeSecond 时，是拿函数返回的那个数去比 -> 只看第 2 个数字。
# "里面有两个元素怎么排序"的答案就在这里：key 已经把它们换成了一个数。
print()
print('=' * 62)
print('第三部分：不写 key vs 写 key=takeSecond')
print('=' * 62)

a = [(2, 2), (3, 4), (4, 1), (1, 3)]
print('不写 key（按整个元组比，先看第 1 个数）：', sorted(a))
print('写 key=takeSecond（只看第 2 个数）：      ', sorted(a, key=takeSecond))
print('原列表 a 没有被改动：', a)


# ============================================================
# 第四部分：key 不一定非要写成函数，lambda 更常用
# ============================================================
# lambda 是"没有名字的小函数"，一行就能写完，意思和 takeSecond 一样。
print()
print('=' * 62)
print('第四部分：用 lambda 代替 takeSecond')
print('=' * 62)

b = [(2, 2), (3, 4), (4, 1), (1, 3)]
print('key=lambda elem: elem[1]  -> ', sorted(b, key=lambda elem: elem[1]))
print('想从大到小，加一个 reverse=True：', sorted(b, key=lambda elem: elem[1], reverse=True))


# ============================================================
# 第五部分：排序是"稳定"的，依据相同的元素保持原来的先后
# ============================================================
print()
print('=' * 62)
print('第五部分：依据相同的时候怎么办（稳定排序）')
print('=' * 62)

# 每个名字后面的数字是"排序依据"，A 和 C 的依据都是 2，B 和 D 都是 1
c = [('A', 2), ('B', 1), ('C', 2), ('D', 1)]
c.sort(key=takeSecond)
print('排序结果：', c)
print('B 原本在 D 前面，依据相同时它俩的顺序就保持不动，A 和 C 也一样。')


# ============================================================
# 第六部分：想按多个条件排，就让 key 返回一个元组
# ============================================================
# 这也是"里面有两个元素怎么排"的另一种答案：
# 如果 key 返回的是一个元组，那么排序时会先比元组的第 0 个，
# 相等再比第 1 个，规则和前面说的字典序完全一样。
print()
print('=' * 62)
print('第六部分：多个条件排序（key 返回元组）')
print('=' * 62)

# 每条数据是 (姓名, 分数, 年龄)
# 需求：分数从高到低；分数一样时，年龄小的排前面
students = [('张三', 90, 20), ('李四', 90, 18), ('王五', 85, 22)]
print('原始数据：', students)

students.sort(key=lambda s: (-s[1], s[2]))   # -分数 = 分数越大越靠前
print('分数降序、同龄按年龄升序：', students)

# 如果只是简单地返回 s[1]，就变成了"按分数升序"
students2 = [('张三', 90, 20), ('李四', 90, 18), ('王五', 85, 22)]
students2.sort(key=lambda s: s[1])
print('只按分数升序：', students2)


