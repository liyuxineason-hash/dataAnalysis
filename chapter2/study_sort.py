# 第七部分：几个容易踩的坑
# ============================================================
print()
print('=' * 62)
print('第七部分：常见坑')
print('=' * 62)

# 坑 1：sort() 是"原地修改"，返回值是 None
d = [3, 1, 2]
result = d.sort()
print(f'd.sort() 的返回值是 {result}，列表 d 本身变成了 {d}')
print('所以不能写 d = d.sort()，那种写法会让 d 变成 None。')
print('不想动原列表就用 sorted(d)，它返回一个新列表：', sorted(d), ' d 还是', d)

# 坑 2：函数名后面不要加括号
print()
print('key=takeSecond   正确：把函数交给 sort，让 sort 自己调用')
print('key=takeSecond() 错误：先调用函数，再把返回值交给 sort')
try:
    [(2, 2), (1, 3)].sort(key=takeSecond())
except TypeError as e:
    print(f'  报错信息：{e}')

# 坑 3：变量名别叫 random
print()
print('原代码里变量名叫 random，会盖住 Python 自带的 random 模块。')
print('本地这样写没问题，但以后想用 random.randint() 就会出怪问题，')
print('建议改成 data、my_list 这类名字。')

# 坑 4：key 函数不能改列表本身，也不该有副作用
print()
